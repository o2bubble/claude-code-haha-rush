#!/usr/bin/env python3
"""Generate an Ed25519 signing keypair for plugin package signing.

Usage:
  python scripts/gen-plugin-key.py

Creates:
  ~/.claude/plugin-signing.key    PRIVATE key (never commit / share / upload!)
  gui/src-tauri/src/plugin_pubkey.rs  PUBLIC key embedded in the GUI binary
                                     (edit + rebuild GUI to distribute)

The private key stays local; publish-plugin.py signs plugin zips with it.
GUI verifies (zip, .sig) tuples against the embedded public key; verification
passes => trusted (installed + "install" button), fails/absent => untrusted
(only "AI install" + AI security review).

Ed25519 (ed25519-dalek in Rust, cryptography in Python) — sign 32-byte SHA256
digest of the zip bytes, signature is 64 bytes (base64 in .sig file).
"""
import os
import sys
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization
import base64

KEY_DIR = os.path.expanduser("~/.claude")
KEY_PATH = os.path.join(KEY_DIR, "plugin-signing.key")
PUB_RUST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                        "gui", "src-tauri", "src", "plugin_pubkey.rs")


def main() -> int:
    os.makedirs(KEY_DIR, exist_ok=True)
    if os.path.exists(KEY_PATH):
        print(f"Key already exists: {KEY_PATH} (delete first to regenerate)")
        return 1

    key = Ed25519PrivateKey.generate()
    priv_raw = key.private_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PrivateFormat.Raw,
        encryption_algorithm=serialization.NoEncryption(),
    )
    pub_raw = key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )

    # Private key: hex, chmod 600 (Windows ignores mode but keep paranoia)
    with open(KEY_PATH, "w", encoding="utf-8") as f:
        f.write(priv_raw.hex() + "\n")
    try:
        os.chmod(KEY_PATH, 0o600)
    except OSError:
        pass

    # Public key embedded in GUI Rust source
    rust = (
        "// Generated by scripts/gen-plugin-key.py — DO NOT EDIT BY HAND.\n"
        "// Re-run the script + rebuild GUI to rotate the plugin signing key.\n"
        "// Public (Ed25519) key used by verify_plugin_signature to validate\n"
        "// plugin packages from the registry. 32 bytes.\n"
        "pub const PLUGIN_PUBKEY: [u8; 32] = [\n"
        + ",\n".join(f"    0x{b:02x}" for b in pub_raw)
        + ",\n];\n"
    )
    with open(PUB_RUST, "w", encoding="utf-8") as f:
        f.write(rust)

    print(f"Private key: {KEY_PATH}")
    print(f"Public key embedded: {PUB_RUST}  (rebuild GUI to take effect)")
    print(f"Public key b64: {base64.b64encode(pub_raw).decode()}")
    print("\n-- DO NOT COMMIT ~/.claude/plugin-signing.key --")
    return 0


if __name__ == "__main__":
    sys.exit(main())
